    public static function get( $key ) {
        $all = self::catalog();
        return isset( $all[ $key ] ) ? $all[ $key ] : null;
    }

    /**
     * رندر HTML راهنما (details تاشو)
     */
    public static function render( $key, $open = false ) {
        $h = self::get( $key );
        if ( ! $h ) {
            return '';
        }
        $open_attr = $open ? ' open' : '';
        $html  = '<details class="cgs-help"' . $open_attr . '>';
        $html .= '<summary>راهنما: ' . esc_html( $h['title'] ) . '</summary>';
        $html .= '<div class="cgs-help-body">';
        $html .= '<p>' . esc_html( $h['body'] ) . '</p>';
        if ( ! empty( $h['steps'] ) && is_array( $h['steps'] ) ) {
            $html .= '<ol>';
            foreach ( $h['steps'] as $s ) {
                $html .= '<li>' . esc_html( $s ) . '</li>';
            }
            $html .= '</ol>';
        }
        if ( ! empty( $h['tip'] ) ) {
            $html .= '<p class="cgs-help-tip"><strong>نکته:</strong> ' . esc_html( $h['tip'] ) . '</p>';
        }
        $html .= '</div></details>';
        return $html;
    }

